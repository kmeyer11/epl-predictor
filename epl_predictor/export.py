"""Build the data file the comparison website reads.

The site (council repo, 03-website-making/sites/epl-predictor) is static: it
loads `data.js`, which sets `window.EPL`. A script file rather than JSON, so
the page also works opened straight from disk without a server.
"""
import json
from collections import defaultdict
from datetime import date, datetime, timezone

from . import db, scoring
from .models import MODELS


def _current_versions():
    return [(name, cls.version) for name, cls in MODELS.items()]


def _leaderboard(rows):
    board, n = scoring.leaderboard(rows, "pick")
    likeliest = {s["model"]: s["pts_per_match"] for s in scoring.leaderboard(rows, "top")[0]}
    return n, [
        {
            "model": s["model"],
            "ptsPerMatch": round(s["pts_per_match"], 3),
            "ptsPerMatchLikeliest": round(likeliest[s["model"]], 3),
            "diffToBest": round(s["diff_to_best"], 3),
            "ci95": round(s["diff_ci95"], 3),
            "exactPct": round(s["exact_pct"], 1),
            "outcomePct": round(s["outcome_pct"], 1),
            "marginPct": round(s["margin_pct"], 1),
            "rps": round(s["rps"], 4),
        }
        for s in board
    ]


def _races(rows, seasons):
    """Cumulative points per backtest refit block (roughly a round), per season and model."""
    names = list(MODELS)
    races = {}
    for season in seasons:
        per_block = defaultdict(lambda: defaultdict(int))
        for r in rows:
            if r["season"] == season:
                per_block[r["created_at"]][r["model"]] += scoring.points(
                    (r["pick_home"], r["pick_away"]), (r["home_goals"], r["away_goals"])
                )
        total = dict.fromkeys(names, 0)
        points = []
        for day in sorted(per_block):
            for m in names:
                total[m] += per_block[day][m]
            points.append({"date": day, **total})
        races[season] = points
    return races


def _upcoming():
    """Saved live bets for matches without a result yet, one entry per match."""
    fixtures = {}
    for r in db.get_unplayed_live_predictions(_current_versions()):
        key = (r["kickoff"], r["home_team"], r["away_team"])
        f = fixtures.setdefault(
            key, {"kickoff": r["kickoff"], "home": r["home_team"], "away": r["away_team"], "bets": {}}
        )
        f["bets"][r["model"]] = {
            "pick": [r["pick_home"], r["pick_away"]],
            "pH": round(r["p_home"], 3),
            "pD": round(r["p_draw"], 3),
            "pA": round(r["p_away"], 3),
            "xg": [round(r["xg_home"], 2), round(r["xg_away"], 2)],
        }
    return sorted(fixtures.values(), key=lambda f: (f["kickoff"], f["home"]))


def build():
    backtest_rows = db.get_scored_predictions("backtest", _current_versions())
    live_rows = db.get_scored_predictions("live", _current_versions())
    seasons = sorted({r["season"] for r in backtest_rows})
    backtest_n, backtest_board = _leaderboard(backtest_rows)
    live_n, live_board = _leaderboard(live_rows)

    by_season = {}
    for season in seasons:
        board, _ = scoring.leaderboard([r for r in backtest_rows if r["season"] == season], "pick")
        by_season[season] = {s["model"]: round(s["pts_per_match"], 3) for s in board}

    return {
        "generatedAt": datetime.now(timezone.utc).isoformat(timespec="minutes"),
        "models": [
            {"name": c.name, "version": c.version, "description": c.description, "benchmark": c.benchmark}
            for c in MODELS.values()
        ],
        "backtest": {
            "matches": backtest_n,
            "seasons": seasons,
            "leaderboard": backtest_board,
            "bySeason": by_season,
            "races": _races(backtest_rows, seasons),
        },
        "live": {"matches": live_n, "leaderboard": live_board},
        "upcoming": _upcoming(),
    }


def write(path):
    data = build()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"// Generated by `epl_predictor.cli export` on {date.today()}. Do not edit.\n"
        f"window.EPL = {json.dumps(data, separators=(',', ':'))};\n"
    )
    return data
